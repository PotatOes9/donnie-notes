export type CopyKey = typeof copyFields[number][0];
export type SiteCopy = Record<CopyKey,string>;
export const defaultCopy = Object.fromEntries(copyFields.map(([key,,,value]) => [key,value])) as SiteCopy;

export function visitorCopy(copy:SiteCopy,fallback:SiteCopy=defaultCopy):SiteCopy {
  const visible = {...copy};
  for (const [key,section] of copyFields) {
    if (section === 8) visible[key] = fallback[key];
  }
  return visible;
}

export function formatCopy(value: string, variables: Record<string,string|number>) {
  return value.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(variables,name) ? String(variables[name]) : match);
}

export function mergeCopy(rows: {key:string;value:string}[]): SiteCopy {
  const copy = {...defaultCopy};
  const seen = new Set<string>();
  for (const {key,value} of rows) {
    if (!Object.hasOwn(defaultCopy,key)) continue;
    if (seen.has(key)) throw new Error('Duplicate website text field');
    seen.add(key);
    if (value.length > 12000) continue;
    // Empty values intentionally hide optional descriptions, but never erase controls.
    const optional = /^(home\.(kicker|established|intro|footnote|scroll|artCaption|artNumber)|footer.tagline|feed.eyebrow|sidebar\.(eyebrow|quoteNote)|about\.(eyebrow|paragraphTwo)|archive.eyebrow|post\.(thanks|nextNote)|error.404eyebrow|settings\.(eyebrow|footnote))$/.test(key);
    if (value.trim() || optional) copy[key as CopyKey] = value;
  }
  return copy;
}
