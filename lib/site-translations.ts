export function localeDefaults(locale:Locale):SiteCopy {
  if(locale==='zh')return {...defaultCopy};
  return Object.fromEntries(copyFields.map(([key])=>[key,translationPairs[key][locale==='ja'?0:1]])) as SiteCopy;
}

export type LocalizedCopyRow={key:string;value:string;ja?:string;en?:string};
export function mergeTranslations(rows:LocalizedCopyRow[],locale:Locale):SiteCopy {
  if(locale==='zh')return mergeCopy(rows);
  const baseline=localeDefaults(locale),source=mergeCopy(rows),seen=new Set<string>();
  for(const row of rows){
    if(!Object.hasOwn(defaultCopy,row.key))continue;
    if(seen.has(row.key))throw new Error('Duplicate website translation field');
    seen.add(row.key);
    const key=row.key as CopyKey,translated=row[locale];
    if(typeof translated==='string'&&translated.trim()&&translated.length<=12000){
      // Reject accidental loss of variables so controls and counts stay meaningful.
      const variables=source[key].match(/\{\w+\}/g)||[];
      if(variables.every(x=>translated.includes(x)))baseline[key]=translated;
    }
    if(!source[key])baseline[key]='';
  }
  return baseline;
}
